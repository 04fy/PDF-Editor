  function detect() {
    var list = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || 'en'];
    for (var i = 0; i < list.length; i++) {
      var tag = String(list[i] || '').toLowerCase();
      if (LANGS[tag]) return tag;
      var base = tag.split('-')[0];
      if (LANGS[base]) return base;
    }
    return 'en';
  }

  function normalise(code) {
    if (LANGS[code]) return code;
    var base = String(code || '').toLowerCase().split('-')[0];
    return LANGS[base] ? base : 'en';
  }

  function create(lang) {
    var current = normalise(lang || detect());
    var api = {
      lang: current,
      meta: META,
      languages: Object.keys(META).map(function (k) { return { code: k, label: META[k].label, dir: META[k].dir }; }),
      dir: function () { return META[current].dir; },
      t: function (key, vars) {
        var table = LANGS[current] || LANGS.en;
        var s = table[key];
        if (s == null) s = LANGS.en[key];
        if (s == null) s = key;
        if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) {
          return vars[k] == null ? m : vars[k];
        });
        return s;
      },
      set: function (code) { current = normalise(code); return current; }
    };
    return api;
  }

